function deepMerge(target, source) {
  for (const k of Object.keys(source)) {
    if (
      source[k] !== null &&
      typeof source[k] === "object" &&
      !Array.isArray(source[k]) &&
      target[k] !== null &&
      typeof target[k] === "object"
    ) {
      target[k] = deepMerge({ ...target[k] }, source[k]);
    } else {
      target[k] = source[k];
    }
  }
  return target;
}

for (const [locale, overrides] of Object.entries(locales)) {
  const path = resolve(messagesDir, `${locale}.json`);
  const current = JSON.parse(readFileSync(path, "utf8"));
  const merged = deepMerge({ ...current }, overrides);
  // Ensure keys that exist only in EN appear in non-EN by walking EN and
  // backfilling missing strings with the EN text (so the UI never sees
  // a "Translation key not found" in the smaller locales).
  const enFull = en;
  const backfill = (target, src) => {
    for (const k of Object.keys(src)) {
      if (typeof src[k] === "string") {
        if (typeof target[k] !== "string") target[k] = src[k];
      } else if (typeof src[k] === "object" && src[k] !== null) {
        if (!target[k] || typeof target[k] !== "object") target[k] = {};
        backfill(target[k], src[k]);
      }
    }
  };
  backfill(merged, enFull);
  writeFileSync(path, JSON.stringify(merged, null, 2) + "\n");
  console.log(`Updated ${locale}.json`);
}